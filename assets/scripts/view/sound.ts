import { AudioClip, AudioSource, Node, resources } from 'cc';
import { makeNode } from './ui-kit';

export type MusicName = 'music-menu' | 'music-game';
export type SfxName =
    | 'sfx-slide' | 'sfx-firefly' | 'sfx-coin' | 'sfx-star' | 'sfx-power'
    | 'sfx-shield' | 'sfx-death' | 'sfx-win' | 'sfx-click';

const ALL: Array<MusicName | SfxName> = [
    'music-menu', 'music-game', 'sfx-slide', 'sfx-firefly', 'sfx-coin', 'sfx-star',
    'sfx-power', 'sfx-shield', 'sfx-death', 'sfx-win', 'sfx-click',
];

const MUSIC_VOLUME = 0.45;
/** Fireflies are collected in quick bursts; cap how often their blip plays. */
const FIREFLY_GAP = 0.05;

/**
 * Music and sound effects, loaded from assets/resources/audio
 * (generated by tools/audio/generate-audio.py).
 */
export class Sound {
    private readonly music: AudioSource;
    private readonly effects: AudioSource;
    private readonly clips = new Map<string, AudioClip>();
    private enabled: boolean;
    private wantedMusic: MusicName | null = null;
    private lastFirefly = -1;
    private time = 0;

    constructor(parent: Node, enabled: boolean) {
        this.enabled = enabled;
        this.music = makeNode('Music', parent).addComponent(AudioSource);
        this.music.loop = true;
        this.music.volume = MUSIC_VOLUME;
        this.effects = makeNode('Effects', parent).addComponent(AudioSource);
        for (const name of ALL) {
            resources.load(`audio/${name}`, AudioClip, (err, clip) => {
                if (err || !clip) {
                    console.warn(`[Sound] cannot load audio/${name}`, err);
                    return;
                }
                this.clips.set(name, clip);
                if (name === this.wantedMusic) this.startMusic();
            });
        }
    }

    get isEnabled(): boolean {
        return this.enabled;
    }

    /** Call every frame with dt; used to throttle rapid effects. */
    tick(dt: number): void {
        this.time += dt;
    }

    playMusic(name: MusicName): void {
        if (this.wantedMusic === name && this.music.playing) return;
        this.wantedMusic = name;
        this.startMusic();
    }

    play(name: SfxName, volume = 1): void {
        if (!this.enabled) return;
        if (name === 'sfx-firefly') {
            if (this.time - this.lastFirefly < FIREFLY_GAP) return;
            this.lastFirefly = this.time;
        }
        const clip = this.clips.get(name);
        if (clip) this.effects.playOneShot(clip, volume);
    }

    setEnabled(on: boolean): void {
        this.enabled = on;
        if (on) this.startMusic();
        else this.music.stop();
    }

    private startMusic(): void {
        const clip = this.wantedMusic ? this.clips.get(this.wantedMusic) : undefined;
        if (!this.enabled || !clip) return; // starts later, when the clip finishes loading
        if (this.music.clip === clip && this.music.playing) return;
        this.music.stop();
        this.music.clip = clip;
        this.music.play();
    }
}
